/* Sdílecí náhled a ikona: python3 -m http.server 8765 v kořeni webu, pak node tools/og.js (potřebuje playwright-core a Google Chrome). */
const { chromium } = require("playwright-core");
const path = require("path");
const fs = require("fs");
const ROOT = path.resolve(__dirname, "..");
const BASE = process.env.BASE || "http://localhost:8765/";
(async () => {
  const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  const p = await b.newPage({ viewport: { width: 1200, height: 630 } });
  await p.goto(BASE + "tools/og.html", { waitUntil: "networkidle" });
  await p.waitForTimeout(400);
  await p.screenshot({ path: path.join(ROOT, "assets/og.jpg"), type: "jpeg", quality: 86 });
  const i = await b.newPage({ viewport: { width: 180, height: 180 } });
  await i.setContent(`<style>html,body{margin:0}</style><img src="${BASE}assets/favicon.svg" width="180" height="180" style="display:block">`);
  await i.waitForTimeout(300);
  await i.screenshot({ path: path.join(ROOT, "assets/apple-touch-icon.png") });
  const note = (file, text) => fs.writeFileSync(path.join(ROOT, file + ".json"), JSON.stringify({ prompt: text, createdAt: new Date().toISOString() }, null, 2) + "\n");
  note("assets/og.jpg", "Origin: screenshot of tools/og.html (own layout: logo, headline in Anybody, graded Pexels photo by Connor Lucock from assets/img/foto/svarenec.webp), captured by tools/og.js. Not generated by an image model.");
  note("assets/apple-touch-icon.png", "Origin: rasterized assets/favicon.svg (own vector mark) by tools/og.js. Not generated by an image model.");
  await b.close();
  console.log("ok og.jpg, apple-touch-icon.png");
})();
