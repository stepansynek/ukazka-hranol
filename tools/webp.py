#!/usr/bin/env python3
"""PNG renderu dílu (s alfou) -> <cíl>-1600.webp a <cíl>-900.webp a k nim původ v .json."""
import datetime as dt
import json
import sys
from pathlib import Path

from PIL import Image

src, dest = Path(sys.argv[1]), sys.argv[2]
im = Image.open(src).convert("RGBA")
# Ořez průhledného okraje: díl s tónovaným stínem vyplní obrázek, kolem zůstane 6 % vzduchu, poměr 4 : 3.
l, t, r, b = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
cx, cy = (l + r) / 2, (t + b) / 2
w, h = (r - l) * 1.12, (b - t) * 1.12
w, h = max(w, h * 4 / 3), max(h, w * 3 / 4)
im = im.crop((round(cx - w / 2), round(cy - h / 2), round(cx + w / 2), round(cy + h / 2)))
name = Path(dest).name.replace("ref-", "")
origin = (f"Origin: own render, not generated by an image model. three.js model of the delivered part ({name}) in "
          f"tools/render-parts.html, lit by the 'náběhové barvy' studio (straw key and bounce, temper-blue rim and fill), "
          f"transparent background, exported to WebP by tools/webp.py.")
for w in (1600, 900):
    out = Path(f"{dest}-{w}.webp")
    im.resize((w, round(im.height * w / im.width)), Image.LANCZOS).save(out, "WEBP", quality=82, method=6)
    out.with_name(out.name + ".json").write_text(json.dumps(
        {"prompt": origin, "createdAt": dt.datetime.now(dt.timezone.utc).isoformat()}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ok", out)
